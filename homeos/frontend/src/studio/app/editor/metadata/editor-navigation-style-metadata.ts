/** 属性面板的一项：分组 + 文案。表里写成 `key: [group, label]`，由 `fieldLabels` 展开。 */
type FieldLabel = { group: string; label: string }
const fieldLabels = <K extends string>(table: Record<K, readonly [string, string]>): Record<K, FieldLabel> =>
  Object.fromEntries(
    (Object.entries(table) as [K, readonly [string, string]][]).map(([key, [group, label]]) => [key, { group, label }]),
  ) as Record<K, FieldLabel>

